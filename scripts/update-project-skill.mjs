import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, mkdirSync, writeFileSync, renameSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, '.agents/skills/project-document/references/source-map.md');
const hash = (value) => createHash('sha256').update(value).digest('hex');
const code = (value) => '`' + value.replaceAll('`', '\\`').replaceAll('\n', ' ') + '`';

function refresh() {
  const files = [...new Set(execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { cwd: root, encoding: 'utf8' }).split('\0'))]
    .filter((file) => /^(app|lib|tests|scripts)\/.*\.(?:[cm]?[jt]sx?|css)$/.test(file) || /^(?:package(?:-lock)?\.json|[^/]+\.config\.[cm]?[jt]s|tsconfig\.json)$/.test(file))
    .sort();
  const records = [];
  for (const file of files) {
    let source;
    try { source = readFileSync(path.join(root, file), 'utf8'); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const imports = [];
    const exports = [];
    for (const statement of ast.statements) {
      if ((ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement)) && statement.moduleSpecifier && ts.isStringLiteral(statement.moduleSpecifier)) imports.push(statement.moduleSpecifier.text);
      if (ts.isExportAssignment(statement)) exports.push('default');
      if (ts.isExportDeclaration(statement)) exports.push(statement.exportClause?.getText(ast) ?? '*');
      if (statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
        if (statement.modifiers.some((modifier) => modifier.kind === ts.SyntaxKind.DefaultKeyword)) exports.push('default');
        else if (ts.isVariableStatement(statement)) exports.push(...statement.declarationList.declarations.map((declaration) => declaration.name.getText(ast)));
        else if (statement.name) exports.push(statement.name.getText(ast));
      }
    }
    records.push({ file, digest: hash(source), imports: [...new Set(imports)].sort(), exports: [...new Set(exports)].sort(), client: ast.statements.some((statement) => ts.isExpressionStatement(statement) && ts.isStringLiteral(statement.expression) && statement.expression.text === 'use client') });
  }
  const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
  const fingerprint = hash(JSON.stringify(records));
  const lines = ['# Generated source snapshot', '', `Source fingerprint: ${code(fingerprint)}`, '', 'Generated by `npm run skill:update`. Structural facts only; hashes track implementation changes. App Router entry files are listed by path (route groups and dynamic segments retain their source spelling).', '', '## Package versions', '', ...Object.entries({ ...pkg.dependencies, ...pkg.devDependencies }).sort().map(([name, version]) => `- ${code(name)}: ${code(version)}`), '', '## Commands', '', ...Object.entries(pkg.scripts).map(([name, command]) => `- ${code(name)}: ${code(command)}`), '', '## App Router entry files', '', ...records.filter(({ file }) => /^app\/(?:.*\/)?(?:page|route)\.[jt]sx?$/.test(file)).map(({ file, exports }) => `- ${code(file)} — exports: ${exports.map(code).join(', ') || 'none'}`), '', '## Source modules', ''];
  for (const record of records) lines.push(`### ${code(record.file)}`, '', `SHA-256: ${code(record.digest)}`, `Client directive: ${record.client ? 'yes' : 'no'}`, `Imports/re-exports: ${record.imports.map(code).join(', ') || 'none'}`, `Exports: ${record.exports.map(code).join(', ') || 'none'}`, '');
  const content = lines.join('\n');
  let previous;
  try { previous = readFileSync(output, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous === content) return false;
  mkdirSync(path.dirname(output), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  writeFileSync(temporary, content);
  renameSync(temporary, output);
  return true;
}

function run() {
  try { console.log(`[${new Date().toISOString()}] project skill: ${refresh() ? 'updated' : 'unchanged'}`); }
  catch (error) { console.error(error); if (!process.argv.includes('--watch')) process.exitCode = 1; }
}

run();
if (process.argv.includes('--watch')) setInterval(run, 300_000);
